#!/bin/bash
# afx-sweep.sh: the ONE scheduled R20 sweep per machine (docs/AFX_WORKING_LOCATIONS.md §4).
# Run every 2h by launchd (Mac: afx-sweep.plist.template) or Task Scheduler (Lenovo, Git Bash).
#   every run  : afx-fragment-audit.sh + 2/4/8h stale-work tiers for every worktree
#                → $AFX_SWEEP_REPORT (default _readiness/FRAGMENTS_LATEST.md)
#   every 8h   : afx-preserve-all.sh (pushes each work branch itself; uncommitted files go to one rolling, self-expiring
#                refs/afx/snapshot/<machine>/<worktree> ref, which is not a branch; never touches worktrees)
#   every 7d   : pnpm store prune
# Report-only apart from preserve's archive branches. Never deletes, never edits a worktree.
# Skips everything (and says so in the report) when preflight says the machine is busy,
# e.g. during an Xcode ship, so it can't compete with real work.
set -u
_AFX_S_DIR="${AFX_GUARD_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)}"
. "$_AFX_S_DIR/afx-platform.sh"

# Single per-machine destination: env, then machine.conf `root=` (launchd has no env), then default.
_MC_ROOT=$(sed -n 's/^root=//p' "$HOME/.claude/hooks/afx-guard/machine.conf" 2>/dev/null | head -1)
ROOT="${AFX_CLONES_ROOT:-${_MC_ROOT:-$(afx_platform_clones_root)}}"
ROOT="${ROOT/#\~/$HOME}"
MACH="${AFX_MACHINE:-$(afx_platform_os)}"
REPORT="${AFX_SWEEP_REPORT:-$(dirname "$ROOT")/_readiness/FRAGMENTS_LATEST.md}"
STATE="$ROOT/.caches/afx-sweep"
# Status that must survive a privacy-blocked ~/Downloads: kept under ~/.claude (not TCC-protected).
# The briefing and status line read this, so a blind sweep is visible instead of silently stale.
STATUS="$HOME/.claude/hooks/afx-guard/sweep-status"
mkdir -p "$(dirname "$STATUS")"
if ! ls "$ROOT" >/dev/null 2>&1 || [ -z "$(ls "$ROOT" 2>/dev/null)" ]; then
  printf 'BLIND %s: cannot read %s (macOS privacy protection on a background job). Grant /bin/bash Full Disk Access or move the AFX root out of ~/Downloads. Nothing was audited or preserved.\n' "$(date '+%Y-%m-%d %H:%M')" "$ROOT" > "$STATUS"
  exit 3
fi
mkdir -p "$STATE" "$(dirname "$REPORT")"
now=$(date +%s)
due() { # due <stamp> <seconds>
  local last=0; [ -f "$STATE/$1" ] && last=$(cat "$STATE/$1" 2>/dev/null || echo 0)
  [ $(( now - last )) -ge "$2" ]
}

tmp="$REPORT.tmp.$$"
{
  echo "# Fragment sweep: $MACH, $(date '+%Y-%m-%d %H:%M %Z')"
  echo
  echo "Generated by scripts/afx-guard/afx-sweep.sh. Policy: docs/AFX_WORKING_LOCATIONS.md."
  echo
  # Control-plane heartbeat (Phase 1): additive, best-effort; a failure is logged, never aborts the sweep.
  hb=$("$_AFX_S_DIR/afx-orchestrate.sh" heartbeat 2>&1) && echo "Heartbeat: $hb" || echo "Heartbeat failed (ignored): $hb"
  echo
  # Runs first (owner 2026-10-20): it is a light file copy, so it must not wait behind the fragment audit and the
  # daily census (up to 40 min) or be skipped when preflight says the machine is busy.
  # Self-update: reinstall the guard when hub main has a newer copy, so a rule merged once
  # reaches every machine within 2h. Reads origin/main via git objects only (the hub main
  # checkout's working tree is never touched), exported to a temp dir and installed from there.
  # machine.conf hub= for nested layouts (the Lenovo keeps the hub under AFX Group\05_TE\AFX Code); flat _clones default.
  _MC_HUB=$(sed -n 's/^hub=//p' "$HOME/.claude/hooks/afx-guard/machine.conf" 2>/dev/null | head -1)
  HUB="${AFX_HUB:-${_MC_HUB:-$ROOT/afx-holding-group}}"
  if [ -d "$HUB/.git" ] && afx_platform_timeout 60 git -C "$HUB" fetch -q origin main 2>/dev/null; then
    new=$(git -C "$HUB" rev-parse --short origin/main:scripts/afx-guard 2>/dev/null)
    have=$(cat "$STATE/guard-tree" 2>/dev/null)
    if [ -n "$new" ] && [ "$new" != "$have" ]; then
      echo
      echo "## Guard self-update"
      tmpd=$(mktemp -d)
      sha=$(git -C "$HUB" rev-parse --short origin/main)
      if git -C "$HUB" archive origin/main scripts/afx-guard | tar -x -C "$tmpd" && AFX_SOURCE_SHA="$sha" bash "$tmpd/scripts/afx-guard/afx-install-claude-hooks.sh" 2>&1; then
        echo "$new" > "$STATE/guard-tree"; echo "installed guard tree $new from origin/main $sha"
        printf '%s %s guard tree %s -> %s (hub %s)\n' "$(date '+%Y-%m-%d %H:%M')" "$MACH" "${have:-none}" "$new" "$sha" >> "$(dirname "$REPORT")/GUARD_UPDATES.log"
      else echo "guard self-update FAILED (kept the installed copy)"; fi
      rm -rf "$tmpd"
    fi
  fi

  if ! "$_AFX_S_DIR/afx-preflight.sh" --clones-root "$ROOT" >/dev/null 2>&1; then
    echo "**Skipped:** preflight says the machine is busy (load/disk). Next run retries."
    exit 0
  fi

  echo "## Stale uncommitted work (2h notice / 4h warn / 8h preserve)"
  echo '```'
  find "$ROOT" -mindepth 3 -maxdepth 4 -type d -path "*/.claude/worktrees/*" 2>/dev/null | while IFS= read -r wt; do
    [ -e "$wt/.git" ] || continue
    "$_AFX_S_DIR/afx-where-am-i.sh" "$wt" 2>&1 >/dev/null
  done
  echo '```'
  echo
  echo "## Fragments (unpushed, stashes, dirty, stray)"
  echo '```'
  afx_platform_timeout 1200 nice -n 15 "$_AFX_S_DIR/afx-fragment-audit.sh" "$ROOT" 2>&1
  echo '```'

  # Branch census (daily): classify every remote branch of every registered repo against its default branch and
  # check the registry against reality (afx-branch-census.sh). Report-only; needs allforx-projects.json, so it runs
  # on the machines that have the registry (the Windows PC) and is skipped elsewhere.
  CREG="${AFX_REGISTRY:-}"
  if [ -z "$CREG" ]; then for _c in "$HOME/Projects/allforx-projects.json" "/c/Users/${USER:-}/Projects/allforx-projects.json"; do [ -f "$_c" ] && { CREG="$_c"; break; }; done; fi
  if [ -n "$CREG" ] && due census 86400; then
    CENSUS_OUT="$(dirname "$REPORT")/BRANCH_CENSUS_LATEST.md"
    echo
    echo "## Branch census (daily)"
    if afx_platform_timeout 2400 nice -n 15 "$_AFX_S_DIR/afx-branch-census.sh" --registry "$CREG" --registry-check --scan-root "$ROOT" --out "$CENSUS_OUT" >/dev/null 2>&1; then
      echo "$now" > "$STATE/census"; echo "written: $CENSUS_OUT"; grep -m1 '^Flagged items' "$CENSUS_OUT"
    else echo "census failed or timed out (report-only; retried next day)"; fi
  fi

  # KPI publish (god-mode AI-efficiency): generate the efficiency envelope to a TEMP file (the repo
  # is never touched, nothing is git-pushed -- protected main rejects that) and POST it to the live
  # hub, signed with the AFX hub-keys scheme (purpose "kpi"): NO separate KPI secret. Best-effort: every
  # failure is reported and the sweep carries on. Needs this machine's hub key and the hub URL, each from
  # env (AFX_HUB_KEY / AFX_HUB_URL), else machine.conf `hub_key=` / `hub_url=` (read like `root=` above);
  # skips cleanly with one line when either is absent. The key goes to the signer through its environment
  # only, and the signature headers to curl on stdin (-K -): neither is ever in argv or the report.
  _MC_HKEY=$(sed -n 's/^hub_key=//p' "$HOME/.claude/hooks/afx-guard/machine.conf" 2>/dev/null | head -1 | tr -d '\r')
  _MC_HURL=$(sed -n 's/^hub_url=//p' "$HOME/.claude/hooks/afx-guard/machine.conf" 2>/dev/null | head -1 | tr -d '\r')
  KPI_HUB_KEY="${AFX_HUB_KEY:-$_MC_HKEY}"
  KPI_HUB_URL="${AFX_HUB_URL:-$_MC_HURL}"
  KPI_PATH="/api/admin/ai-efficiency"
  # Cost posture (owner directive 2026-10-21): each POST wakes the paid hub app, and two machines send. At most one POST per day when
  # parked (the hub dashboard still gets its daily number), a 6 h floor when live. The stamp is written after every attempt that
  # reached curl (success or not), so a failing hub is not hit every 2 h cycle; override the floor with AFX_KPI_FLOOR_S (tests).
  KPI_POSTURE=$(afx_posture_resolve | cut -d' ' -f1)
  if [ "$KPI_POSTURE" = live ]; then KPI_FLOOR_S="${AFX_KPI_FLOOR_S:-21600}"; else KPI_FLOOR_S="${AFX_KPI_FLOOR_S:-86400}"; fi
  PUB="$HUB/scripts/afx-guard/afx-publish-kpis.sh"
  SIGNER="$_AFX_S_DIR/afx-kpi-sign.mjs"
  echo
  if [ -z "$KPI_HUB_KEY" ] || [ -z "$KPI_HUB_URL" ]; then
    echo "## KPI publish: skipped (no hub_key/hub_url: set AFX_HUB_KEY + AFX_HUB_URL or hub_key=/hub_url= in machine.conf; see HUMAN_ACTIONS.md)"
  elif ! due kpi-sent "$KPI_FLOOR_S"; then
    echo "## KPI publish: skipped (already sent within the last $((KPI_FLOOR_S/3600))h; posture $KPI_POSTURE; stamp $STATE/kpi-sent)"
  elif [ ! -x "$PUB" ] || [ ! -f "$SIGNER" ] || ! command -v curl >/dev/null 2>&1 || ! command -v node >/dev/null 2>&1; then
    echo "## KPI publish: skipped (publisher, signer, curl or node missing)"
  else
    echo "## KPI publish (god-mode AI-efficiency)"
    kpitmp=$(mktemp "${TMPDIR:-/tmp}/afx-kpi.XXXXXX"); chmod 600 "$kpitmp"
    if afx_platform_timeout 90 bash "$PUB" --out "$kpitmp" >/dev/null 2>&1 && [ -s "$kpitmp" ]; then
      kpihdrs=$(AFX_HUB_KEY="$KPI_HUB_KEY" afx_platform_timeout 20 node "$SIGNER" --venture ops-sweep --path "$KPI_PATH" --body "$kpitmp" 2>/dev/null)
      if [ -z "$kpihdrs" ]; then
        echo "kpi-publish: signing failed (check hub_key) -- skipped (best-effort)"
      else
        kpicode=$(printf '%s\n' "$kpihdrs" | sed 's/^\(.*\)$/header = "\1"/' \
          | afx_platform_timeout 60 curl -sS -K - --max-time 30 -o /dev/null -w '%{http_code}' \
              -X POST -H 'Content-Type: application/json' --data-binary "@$kpitmp" "${KPI_HUB_URL%/}$KPI_PATH" 2>/dev/null)
        kpirc=$?
        echo "$now" > "$STATE/kpi-sent"
        echo "kpi-publish: curl exit=$kpirc http_status=${kpicode:-none}"
        case "${kpicode:-}" in
          200) echo "kpi-publish: published" ;;
          *)   echo "kpi-publish: NOT published (best-effort, sweep continues; retry after the daily window; posture $KPI_POSTURE)" ;;
        esac
      fi
    else echo "kpi-publish: generator errored or timed out -- skipped (best-effort)"; fi
    rm -f "$kpitmp"
  fi
  unset KPI_HUB_KEY _MC_HKEY

  if due preserve 28800; then
    echo
    echo "## Preserve (every 8h)"
    echo '```'
    afx_platform_timeout 1800 nice -n 15 "$_AFX_S_DIR/afx-preserve-all.sh" "$MACH" "$ROOT" 2>&1 && echo "$now" > "$STATE/preserve"
    echo '```'
  fi

  # Git integrity (weekly, read-only): the 2026-09-27 NTFS/Drive incident left a corrupt pack in the Lenovo hub clone
  # that went unnoticed until a checkout failed on 2026-10-20. fsck --connectivity-only reads every object's links;
  # failures go to the report and to ~/.claude/hooks/afx-guard/git-integrity, which the session briefing shows in red.
  if due fsck 604800; then
    echo
    echo "## Git integrity (weekly fsck --connectivity-only)"
    GI="$HOME/.claude/hooks/afx-guard/git-integrity"; bad=""; n=0
    while IFS= read -r g; do
      r=$(dirname "$g"); n=$((n+1))
      afx_platform_timeout 900 nice -n 15 git -C "$r" fsck --connectivity-only --no-dangling >/dev/null 2>&1 || bad="$bad $r"
    done < <(find "$ROOT" -mindepth 2 -maxdepth 5 -type d -name .git -not -path "*/node_modules/*" -not -path "*/.claude/worktrees/*" 2>/dev/null)
    if [ -n "$bad" ]; then
      printf 'BAD %s:%s\n' "$(date '+%Y-%m-%d %H:%M')" "$bad" > "$GI"; echo "FAILED:$bad (of $n clones). Do not gc or prune; see docs/AFX_SESSION_QUICKSTART.md troubleshooting."
    else
      printf 'OK %s: %s clones\n' "$(date '+%Y-%m-%d %H:%M')" "$n" > "$GI"; echo "OK: $n clones"
    fi
    echo "$now" > "$STATE/fsck"
  fi

  if due prune 604800 && command -v pnpm >/dev/null 2>&1; then
    echo
    echo "## pnpm store prune (weekly)"
    echo '```'
    afx_platform_timeout 900 nice -n 15 pnpm store prune 2>&1 | tail -3 && echo "$now" > "$STATE/prune"
    echo '```'
  fi
} > "$tmp" 2>&1
if mv "$tmp" "$REPORT" 2>/dev/null || { cat "$tmp" > "$REPORT" 2>/dev/null && rm -f "$tmp"; }; then
  printf 'OK %s: %s\n' "$(date '+%Y-%m-%d %H:%M')" "$REPORT" > "$STATUS"
else
  mv "$tmp" "$HOME/.claude/hooks/afx-guard/FRAGMENTS_LATEST.md" 2>/dev/null
  printf 'BLIND %s: could not write %s (privacy protection); report kept at ~/.claude/hooks/afx-guard/FRAGMENTS_LATEST.md\n' "$(date '+%Y-%m-%d %H:%M')" "$REPORT" > "$STATUS"
fi
