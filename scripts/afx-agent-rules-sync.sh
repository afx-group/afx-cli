#!/bin/bash
# afx-agent-rules-sync.sh: render the AFX operating rules into the files every AI tool reads, from ONE template.
#
#   afx-agent-rules-sync.sh [--write] <repo-path>     write/refresh the managed blocks (default mode)
#   afx-agent-rules-sync.sh --check <repo-path>       read-only; exit 1 if any file is missing or has drifted
#   afx-agent-rules-sync.sh --list                    print the target files (repo-relative)
#   afx-agent-rules-sync.sh --print                   print the rendered block to stdout
#
# Source of truth: scripts/afx-guard/agent-rules/afx-agent-rules.template.md (hub). Targets, all inside the repo:
#   AGENTS.md                                 universal (Codex, Cursor, Aider, Copilot agents, VS Code)
#   replit.md                                 Replit Agent
#   .cursor/rules/afx-operating-standard.mdc Cursor (alwaysApply)
#   .github/copilot-instructions.md           GitHub Copilot
#   CONVENTIONS.md                            Aider / local AI (aider --read CONVENTIONS.md)
#   CLAUDE.md                                 only a 2-line link to AGENTS.md, and only if CLAUDE.md already exists
# Existing file content is preserved: only the text between the AFX-AGENT-RULES markers is owned by this script;
# when a file has no markers yet, the block is appended. Never overwrites, never deletes, never runs git.
# Exit: 0 ok / in sync, 1 drift (--check only), 2 usage error. Portable: macOS bash 3.2 + BSD userland.
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
TEMPLATE="${AFX_AGENT_RULES_TEMPLATE:-$HERE/agent-rules/afx-agent-rules.template.md}"
# The full template is private-tier (a tenant's own rules); a core-only tree falls back to the neutral starter set.
[ -f "$TEMPLATE" ] || [ -n "${AFX_AGENT_RULES_TEMPLATE:-}" ] || TEMPLATE="$HERE/agent-rules/afx-agent-rules.default.md"
BEGIN='<!-- AFX-AGENT-RULES:BEGIN generated by afx-agent-rules-sync.sh; do not edit -->'
END='<!-- AFX-AGENT-RULES:END -->'
LBEGIN='<!-- AFX-AGENT-RULES-LINK:BEGIN -->'
LEND='<!-- AFX-AGENT-RULES-LINK:END -->'
TARGETS="AGENTS.md replit.md .cursor/rules/afx-operating-standard.mdc .github/copilot-instructions.md CONVENTIONS.md"
MDC_HEAD='---
description: AFX operating standard (branches, no .env edits, migrations via sanctioned tooling, honest gates)
alwaysApply: true
---
'

MODE=write; REPO=""
while [ $# -gt 0 ]; do
  case "$1" in
    --check) MODE=check ;; --write) MODE=write ;;
    --list) printf '%s\nCLAUDE.md (link block, if present)\n' $TARGETS | tr ' ' '\n' | sed '/^$/d'; exit 0 ;;
    --print) MODE=print ;;
    -h|--help) sed -n '2,/^set -u/p' "${BASH_SOURCE[0]:-$0}" | sed '$d;s/^# \{0,1\}//'; exit 0 ;;
    -*) echo "afx-agent-rules-sync: unknown option $1" >&2; exit 2 ;;
    *) REPO="$1" ;;
  esac; shift
done
[ -f "$TEMPLATE" ] || { echo "afx-agent-rules-sync: template not found: $TEMPLATE" >&2; exit 2; }
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

# block files: managed block (rules) and link block (CLAUDE.md)
{ printf '%s\n' "$BEGIN"; cat "$TEMPLATE"; printf '%s\n' "$END"; } > "$TMP/block"
{ printf '%s\n' "$LBEGIN"; printf '%s\n' "Tool-neutral AFX operating rules for every AI tool: see [AGENTS.md](AGENTS.md) (generated from the hub). The Agent operating standard section in this file stays authoritative for Claude Code."; printf '%s\n' "$LEND"; } > "$TMP/link"

if [ "$MODE" = print ]; then cat "$TMP/block"; exit 0; fi
[ -n "$REPO" ] || { echo "afx-agent-rules-sync: repo path required" >&2; exit 2; }
[ -d "$REPO" ] || { echo "afx-agent-rules-sync: not a directory: $REPO" >&2; exit 2; }
REPO="$(cd "$REPO" && pwd -P)"

# compose <existing-file-or-empty> <blockfile> <begin> <end> <header>  -> new content on stdout
compose() {
  local f="$1" blk="$2" b="$3" e="$4" head="$5"
  if [ -f "$f" ] && grep -qF "$b" "$f"; then
    awk -v b="$b" -v e="$e" -v blk="$blk" '
      index($0,b)==1 && !done { while ((getline l < blk) > 0) print l; skip=1; done=1; next }
      skip && index($0,e)==1 { skip=0; next }
      !skip { print }' "$f"
  elif [ -f "$f" ]; then
    cat "$f"; [ -n "$(tail -c1 "$f")" ] && echo; [ -s "$f" ] && echo; cat "$blk"
  else
    [ -n "$head" ] && printf '%s\n' "$head"; cat "$blk"
  fi
}

DRIFT=0; N=0
handle() { # handle <relpath> <blockfile> <begin> <end> <header>
  local rel="$1" f="$REPO/$1" st
  N=$((N+1))
  compose "$f" "$2" "$3" "$4" "$5" > "$TMP/new"
  if [ -f "$f" ] && cmp -s "$f" "$TMP/new"; then echo "OK    $rel"; return; fi
  if [ -f "$f" ]; then st=stale; else st=missing; fi
  if [ "$MODE" = check ]; then echo "DRIFT $rel ($st)"; DRIFT=$((DRIFT+1)); return; fi
  mkdir -p "$(dirname "$f")" && cp "$TMP/new" "$f" && echo "WROTE $rel ($st -> synced)"
}

for t in $TARGETS; do
  case "$t" in *.mdc) handle "$t" "$TMP/block" "$BEGIN" "$END" "$MDC_HEAD" ;; *) handle "$t" "$TMP/block" "$BEGIN" "$END" "" ;; esac
done
[ -f "$REPO/CLAUDE.md" ] && handle CLAUDE.md "$TMP/link" "$LBEGIN" "$LEND" ""

if [ "$MODE" = check ]; then
  echo "agent-rules: $DRIFT of $N file(s) drifted in $REPO"
  [ "$DRIFT" -gt 0 ] && exit 1
fi
exit 0
